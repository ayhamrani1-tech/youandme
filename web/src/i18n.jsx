const I18nContext = createContext(null);

function detectLocale() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'ar' || stored === 'en') return stored;
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== 'undefined' && /^ar\b/i.test(navigator.language || '') ? 'ar' : 'ar';
}

export function I18nProvider({ children }) {
  const [locale, setLocale] = useState(detectLocale);

  useEffect(() => {
    const dir = locale === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = locale;
    document.documentElement.dir = dir;
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      /* storage unavailable */
    }
  }, [locale]);

  const t = useCallback(
    (key, vars) => {
      let text = DICTIONARY[locale][key] ?? DICTIONARY.ar[key] ?? key;
      if (vars) {
        for (const [name, value] of Object.entries(vars)) {
          text = text.replaceAll(`{${name}}`, String(value));
        }
      }
      return text;
    },
    [locale],
  );

  const value = useMemo(
    () => ({
      locale,
      dir: locale === 'ar' ? 'rtl' : 'ltr',
      isRtl: locale === 'ar',
      t,
      setLocale,
      toggle: () => setLocale((current) => (current === 'ar' ? 'en' : 'ar')),
      /** Pick the right side of a `{ ar, en }` pair from the API. */
      pick: (pair) => {
        if (!pair) return '';
        if (typeof pair === 'string') return pair;
        return (locale === 'ar' ? pair.ar : pair.en) || pair.ar || pair.en || '';
      },
      /** Localised date and time, always with Western digits. */
      formatDate: (value, options) =>
        value
          ? new Date(value).toLocaleDateString(locale === 'ar' ? 'ar-JO-u-nu-latn' : 'en-GB', {
              day: 'numeric',
              month: 'short',
              ...options,
            })
          : '',
      formatTime: (value) =>
        value
          ? new Date(value).toLocaleTimeString(locale === 'ar' ? 'ar-JO-u-nu-latn' : 'en-GB', {
              hour: '2-digit',
              minute: '2-digit',
              hour12: false,
            })
          : '',
      formatMoney: (amount) =>
        `${Number(amount ?? 0).toFixed(2)} ${DICTIONARY[locale]['common.currency']}`,
    }),
    [locale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}

/** Translate an API error code, falling back to its message. */
export function useErrorMessage() {
  const { t, locale } = useI18n();
  return useCallback(
    (error) => {
      if (!error) return '';
      const code = error.code || error?.error?.code;
      if (code && DICTIONARY[locale][`error.${code}`]) return t(`error.${code}`);
      return error.message || error?.error?.message || t('error.generic');
    },
    [t, locale],
  );
}
